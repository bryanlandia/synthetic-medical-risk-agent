"""Documentation-setting profiles for LLM-written notes.

A profile fixes the form of a note (what is stated, how much, and how) and drives both the note plan
(what the note must say) and the setting's prompt (how it reads). These are plausible stand-ins for
clinician-authored documentation, not a verified catalog of any vendor's templates.
"""

from __future__ import annotations

from dataclasses import dataclass

from .config import LLM_SETTINGS


@dataclass(frozen=True)
class SettingProfile:
    name: str
    description: str  # shown to the writer model
    min_labs: int
    max_labs: int | None  # None = state every non-missing lab
    max_negatives: int | None  # cap on negated symptoms stated; None = no cap
    show_flags: bool  # H/L flags next to lab values
    show_ref_ranges: bool
    stale_rate_multiplier: float  # scales the configured stale-value rate
    hedge_rate_multiplier: float  # scales the configured hedge rate
    quote_patient: bool  # may include the patient's own words


PROFILES: dict[str, SettingProfile] = {
    "shorthand": SettingProfile(
        name="shorthand",
        description=(
            "A rushed outpatient note in clinician shorthand: abbreviations, sentence fragments, only the "
            "headline items. No paragraphs."
        ),
        min_labs=2, max_labs=3, max_negatives=2,
        show_flags=False, show_ref_ranges=False,
        stale_rate_multiplier=1.0, hedge_rate_multiplier=1.0, quote_patient=False,
    ),
    "ehr_template": SettingProfile(
        name="ehr_template",
        description=(
            "A specialist follow-up visit written in an EHR template: a short typed history, a review of "
            "systems grouped by body system (Neuro, Eyes, MSK, General), a results block that lists each lab "
            "with its high or low flag and reference range, and a brief monitoring plan."
        ),
        min_labs=1, max_labs=None, max_negatives=None,
        show_flags=True, show_ref_ranges=True,
        stale_rate_multiplier=1.0, hedge_rate_multiplier=0.5, quote_patient=False,
    ),
    "ai_scribe": SettingProfile(
        name="ai_scribe",
        description=(
            "A visit summary generated by an ambient AI scribe from the conversation: flowing narrative "
            "prose in complete sentences, attributing statements to the patient, often hedged ('reports', "
            "'seems to', 'maybe'), mentioning labs only in passing."
        ),
        min_labs=0, max_labs=3, max_negatives=2,
        show_flags=False, show_ref_ranges=False,
        stale_rate_multiplier=1.0, hedge_rate_multiplier=1.5, quote_patient=True,
    ),
    "copy_forward": SettingProfile(
        name="copy_forward",
        description=(
            "A progress note assembled by copying the previous visit's note forward and editing it: "
            "unchanged boilerplate, some carried-over text, then a few updated lines. Carried-over values "
            "are not labelled as old."
        ),
        min_labs=2, max_labs=5, max_negatives=None,
        show_flags=False, show_ref_ranges=False,
        stale_rate_multiplier=4.0, hedge_rate_multiplier=1.0, quote_patient=False,
    ),
}

assert set(PROFILES) == set(LLM_SETTINGS), "every LLM setting needs exactly one profile"
